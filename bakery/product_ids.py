def product_id_expression(prefix=''):
    """Resolve IDs in SQL so filtering/sorting happens before pagination.

    The shared SKU needs the Nelson source's VendorsId (or its preserved
    compound internal code). Without that evidence, leave the ID unknown.
    """
    ids_by_sku = {}
    for product_id, sku in PRODUCT_ID_ROWS:
        ids_by_sku.setdefault(sku, []).append(product_id)
    cases = []
    for sku, product_ids in ids_by_sku.items():
        match_sku = Q(**{prefix + 'sku': sku})
        if len(product_ids) == 1:
            cases.append(When(match_sku, then=Value(product_ids[0])))
            continue
        # Prefer explicit source provenance over the generated internal code.
        for product_id in product_ids:
            cases.append(When(
                match_sku & Q(**{prefix + 'source_record__values__VendorsId': product_id}),
                then=Value(product_id),
            ))
        for product_id in product_ids:
            cases.append(When(
                match_sku & Q(**{prefix + 'internal_product_code': f'{sku}-{product_id}'}),
                then=Value(product_id),
            ))
    return Case(*cases, default=Value(None), output_field=CharField())
